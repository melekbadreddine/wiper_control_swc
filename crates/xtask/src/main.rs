//! Dev automation CLI. Commands:
//!
//! - `traceability` — scan `docs/requirements.md` and the crate sources, emit
//!   `docs/traceability.md`, print counts, `--strict` exits non-zero if any
//!   requirement is neither verified in code nor explicitly marked as planned
//!   (`(Mx)` marker). Local `make traceability` stays non-strict until M5; CI
//!   switches to strict (documented in AGENTS.md).

#![forbid(unsafe_code)]

use std::fmt::Write as _; //_cli
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Debug)]
enum Status {
    Verified,
    Planned,
    Missing,
}

#[derive(Debug)]
struct Req {
    id: String,
    tests: Vec<String>,
    /// Row was explicitly marked with a future milestone, e.g. `arxml_consistency_ports (M6)`.
    planned: bool,
}

fn collect_rs_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = fs::read_dir(dir) else {
        return;
    };
    for entry in entries.into_iter().flatten() {
        let path = entry.path();
        if path.is_dir() {
            if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
                if name == "target" || name.starts_with('.') {
                    continue;
                }
            }
            collect_rs_files(&path, out);
        } else if path.extension().and_then(|e| e.to_str()) == Some("rs") {
            out.push(path);
        }
    }
}

/// Table rows in `docs/requirements.md` look like:
/// `| REQ-WIP-003 | Title | text | design | test1 test2 (M6) |`
/// Rows with fewer than 5 cells (e.g. the safety-goal table) are not tracked.
fn parse_requirements(md: &str) -> Vec<Req> {
    let mut reqs = Vec::new();
    for line in md.lines() {
        let trimmed = line.trim();
        if !trimmed.starts_with("| REQ-WIP-") {
            continue;
        }
        let cells: Vec<&str> = trimmed
            .trim_start_matches('|')
            .split('|')
            .filter(|c| !c.trim().is_empty())
            .collect();
        if cells.len() < 5 {
            continue;
        }
        let tests_cell = cells.last().copied().unwrap_or("");
        let planned = tests_cell.contains("(M");
        let tests = tests_cell
            .split([' ', ',', ';'])
            .map(str::trim)
            .filter(|t| !t.is_empty() && !t.starts_with("(M"))
            .map(str::to_string)
            .collect();
        reqs.push(Req {
            id: cells.first().copied().unwrap_or("").trim().to_string(),
            tests,
            planned,
        });
    }
    reqs
}

fn status_for(req: &Req, sources: &str, _md: &str) -> Status {
    if sources.contains(&format!("verifies: {}", req.id)) {
        return Status::Verified;
    }
    let tested = req
        .tests
        .iter()
        .any(|t| !t.contains("(M") && sources.contains(&format!("fn {t}(")));
    if tested {
        return Status::Verified;
    }
    if req.planned {
        return Status::Planned;
    }
    Status::Missing
}

fn label(st: &Status) -> &str {
    match st {
        Status::Verified => "VERIFIED",
        Status::Planned => "PLANNED",
        Status::Missing => "MISSING",
    }
}

fn write_report(reqs: &[Req], statuses: &[Status]) -> std::io::Result<()> {
    let mut out = String::from(
        "# Requirements traceability\n\nGenerated by `cargo xtask traceability` from \
         `docs/requirements.md` and the sources under `crates/`. VERIFIED = a `// \
         verifies: <ID>` tag or the declared test name was found in real source files.\n\n\
         | ID | Status | Tests |\n|---|---|---|\n",
    );
    for (req, st) in reqs.iter().zip(statuses) {
        let tests = if req.tests.is_empty() {
            "—".to_string()
        } else {
            req.tests.join(", ")
        };
        writeln!(out, "| {} | {} | {} |", req.id, label(st), tests).ok();
    }
    let (mut v, mut p, mut m) = (0, 0, 0);
    for s in statuses {
        match s {
            Status::Verified => v += 1,
            Status::Planned => p += 1,
            Status::Missing => m += 1,
        }
    }
    write!(
        out,
        "\n**Summary:** {v} verified, {p} planned, {m} missing.\n"
    )
    .ok();
    fs::write("docs/traceability.md", out)
}

fn main() -> std::process::ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let strict = args.iter().any(|a| a == "--strict");
    let cmd = args
        .iter()
        .find(|a| !a.starts_with("--"))
        .map(String::as_str);
    match cmd {
        Some("traceability") => {
            let md = match fs::read_to_string("docs/requirements.md") {
                Ok(md) => md,
                Err(e) => {
                    eprintln!("traceability: cannot read docs/requirements.md: {e}");
                    return std::process::ExitCode::from(1);
                }
            };
            let reqs = parse_requirements(&md);
            let mut files = Vec::new();
            collect_rs_files(Path::new("crates"), &mut files);
            let mut sources = md.clone();
            for f in &files {
                if let Ok(text) = fs::read_to_string(f) {
                    sources.push('\n');
                    sources.push_str(&text);
                }
            }
            let statuses: Vec<Status> = reqs.iter().map(|r| status_for(r, &sources, &md)).collect();
            let missing = statuses
                .iter()
                .filter(|s| matches!(s, Status::Missing))
                .count();
            if let Err(e) = write_report(&reqs, &statuses) {
                eprintln!("traceability: cannot write report: {e}");
                return std::process::ExitCode::from(1);
            }
            let (v, p) = (
                statuses
                    .iter()
                    .filter(|s| matches!(s, Status::Verified))
                    .count(),
                statuses
                    .iter()
                    .filter(|s| matches!(s, Status::Planned))
                    .count(),
            );
            println!("traceability: {v} verified, {p} planned, {missing} missing");
            if strict && missing > 0 {
                eprintln!("traceability --strict: {missing} requirement(s) have no test");
                return std::process::ExitCode::from(1);
            }
            std::process::ExitCode::SUCCESS
        }
        Some(other) => {
            eprintln!("xtask: unknown command '{other}' (try `traceability`)");
            std::process::ExitCode::from(2)
        }
        None => {
            eprintln!("usage: cargo xtask <traceability> [--strict]");
            std::process::ExitCode::from(2)
        }
    }
}
